def find_java():
    candidates = []
    if "JAVA_HOME" in os.environ:
        candidates.append(os.path.join(os.environ["JAVA_HOME"], "bin", "java.exe"))
        candidates.append(os.path.join(os.environ["JAVA_HOME"], "bin", "java"))
    for root in [r"C:\Program Files\Java", r"C:\Program Files (x86)\Java"]:
        if os.path.isdir(root):
            for d in sorted(os.listdir(root), reverse=True):
                candidates.append(os.path.join(root, d, "bin", "java.exe"))
    candidates.append("java")
    for c in candidates:
        if c and (os.path.exists(c) or c == "java"):
            try:
                res = subprocess.run([c, "-version"], capture_output=True, text=True, timeout=5)
                out = res.stderr or res.stdout
                if "1.8" not in out and any(v in out for v in ["11", "17", "21", "24", "25"]):
                    return c
            except Exception:
                pass
    return "java"

JAVA_EXEC = find_java()

def parse_block_log(log_path):
    """
    Parses a block log generated by BenchmarkRunner:
    Block #  1 (cycles      1..  5000, 10000 ops):    3.67 ms | TOMB:   4967 (0.47%) | EMPTY: 519321 (49.53%) | DIB avg/max: 0.511/40 | Rebuilds: 0 (+0)
    """
    blocks = []
    if not os.path.exists(log_path):
        return blocks
    
    pattern = re.compile(
        r"Block\s+#\s*(\d+)\s*\(cycles\s*(\d+)\.\.\s*(\d+),\s*(\d+)\s+ops\):\s*([\d\.]+)\s+ms\s*\|\s*TOMB:\s*(\d+)\s*\(([\d\.]+)%\)\s*\|\s*EMPTY:\s*(\d+)\s*\(([\d\.]+)%\)\s*\|\s*DIB avg/max:\s*([\d\.-]+)/([\d-]+)\s*\|\s*Rebuilds:\s*(-?\d+)\s*\(\+?(-?\d+)\)"
    )

    with open(log_path, "r", encoding="utf-8", errors="replace") as f:
        for line in f:
            m = pattern.search(line)
            if m:
                block_idx = int(m.group(1))
                start_c = int(m.group(2))
                end_c = int(m.group(3))
                ops = int(m.group(4))
                elapsed_ms = float(m.group(5))
                tomb_cnt = int(m.group(6))
                tomb_pct = float(m.group(7))
                empty_cnt = int(m.group(8))
                empty_pct = float(m.group(9))
                avg_dib = float(m.group(10))
                max_dib = int(m.group(11))
                rebuild_cnt = int(m.group(12))
                rebuilds_in_block = int(m.group(13))

                blocks.append({
                    "block_index": block_idx,
                    "start_cycle": start_c,
                    "end_cycle": end_c,
                    "ops_count": ops,
                    "elapsed_ms": elapsed_ms,
                    "tombstone_count": tomb_cnt,
                    "tombstone_ratio": tomb_pct / 100.0,
                    "empty_count": empty_cnt,
                    "empty_ratio": empty_pct / 100.0,
                    "average_dib": avg_dib,
                    "max_dib": max_dib,
                    "rebuild_count": max(0, rebuild_cnt),
                    "rebuilds_in_block": max(0, rebuilds_in_block)
                })
    return blocks

def run_workload_profiling(root_dir):
    jar_path = os.path.join(root_dir, "HashTableProject", "dist", "HashTableProject.jar")
    temp_dir = os.path.join(root_dir, "scratch", "block_logs")
    os.makedirs(temp_dir, exist_ok=True)

    configs = [
        {"alpha": 0.50, "tau": "0.20", "label": "alpha050"},
        {"alpha": 0.80, "tau": "0.10", "label": "alpha080"}
    ]
    algos = ["lp-tomb", "lp-backshift", "rh", "rh-noearly"]

    all_block_records = {"alpha050": [], "alpha080": []}
    summary_records = []

    print("=" * 70)
    print(" BẮT ĐẦU CHẠY PHÂN TÍCH KHỐI 10^4 THAO TÁC WORKLOAD CHURN CHO RQ3")
    print(f" Java runtime: {JAVA_EXEC}")
    print("=" * 70)

    for cfg in configs:
        alpha = cfg["alpha"]
        tau_tomb = cfg["tau"]
        lbl = cfg["label"]
        print(f"\n>>> Thực nghiệm chế độ tải sống alpha = {alpha:.2f} (M = 1,048,576, C = 4,194,304)")

        for algo in algos:
            tau = tau_tomb if algo == "lp-tomb" else "Infinity"
            log_file = os.path.join(temp_dir, f"block_{algo}_{lbl}.log")
            if os.path.exists(log_file):
                os.remove(log_file)

            cmd = [
                JAVA_EXEC, "-Xmx2g", "-jar", jar_path,
                "--algo", algo,
                "--tau", tau,
                "--m", "1048576",
                "--alpha", str(alpha),
                "--c", "4194304",
                "--seed", "42",
                "--mode", "time",
                "--query", "hit",
                "--block-log", log_file,
                "--csv-only"
            ]

            t0 = time.time()
            proc = subprocess.run(cmd, capture_output=True, text=True, cwd=root_dir)
            wall_time = time.time() - t0

            if proc.returncode != 0:
                print(f"[LỖI] Thuật toán {algo} thất bại (code {proc.returncode}): {proc.stderr}")
                continue

            blocks = parse_block_log(log_file)
            print(f"  + {algo:14s}: {len(blocks)} khối, wall-clock: {wall_time:.2f}s")

            # Collect block times
            times = [b["elapsed_ms"] for b in blocks]
            total_churn_ms = sum(times)
            med_time = statistics.median(times) if times else 0.0
            max_time = max(times) if times else 0.0
            total_rebuilds = blocks[-1]["rebuild_count"] if blocks else 0

            # Rebuild blocks
            rebuild_blocks = [b for b in blocks if b["rebuilds_in_block"] > 0]
            rebuild_block_times = [b["elapsed_ms"] for b in rebuild_blocks]
            normal_block_times = [b["elapsed_ms"] for b in blocks if b["rebuilds_in_block"] == 0]

            med_normal = statistics.median(normal_block_times) if normal_block_times else 0.0
            avg_rebuild_time = (sum(rebuild_block_times) - med_normal * len(rebuild_block_times)) if rebuild_blocks else 0.0
            avg_rebuild_time = max(0.0, avg_rebuild_time)

            final_b = blocks[-1] if blocks else {}
            final_avg_dib = final_b.get("average_dib", 0.0)
            final_max_dib = final_b.get("max_dib", 0)
            final_tomb_ratio = final_b.get("tombstone_ratio", 0.0)
            final_empty_ratio = final_b.get("empty_ratio", 0.0)

            summary_records.append({
                "load_factor": alpha,
                "algorithm": algo,
                "variant": "noearly" if algo == "rh-noearly" else "base",
                "tau": tau,
                "churn_cycles": 4194304,
                "total_blocks": len(blocks),
                "total_churn_time_ms": round(total_churn_ms, 2),
                "median_block_ms": round(med_time, 2),
                "max_block_ms": round(max_time, 2),
                "rebuild_count": total_rebuilds,
                "rebuild_overhead_ms": round(avg_rebuild_time, 2),
                "average_dib": round(final_avg_dib, 4),
                "max_dib": final_max_dib,
                "tombstone_ratio": round(final_tomb_ratio, 4),
                "empty_ratio": round(final_empty_ratio, 4)
            })

            # Record per-block entries
            for b in blocks:
                b_entry = dict(b)
                b_entry["algorithm"] = algo
                b_entry["alpha"] = alpha
                all_block_records[lbl].append(b_entry)

    # 1. Export block profiling CSVs
    raw_dir = os.path.join(root_dir, "results", "raw")
    os.makedirs(raw_dir, exist_ok=True)

    for lbl, records in all_block_records.items():
        out_csv = os.path.join(raw_dir, f"rq3_block_profiling_{lbl}.csv")
        fieldnames = [
            "alpha", "algorithm", "block_index", "start_cycle", "end_cycle",
            "ops_count", "elapsed_ms", "tombstone_count", "tombstone_ratio",
            "empty_count", "empty_ratio", "average_dib", "max_dib",
            "rebuild_count", "rebuilds_in_block"
        ]
        with open(out_csv, "w", newline="", encoding="utf-8") as f:
            writer = csv.DictWriter(f, fieldnames=fieldnames)
            writer.writeheader()
            writer.writerows(records)
        print(f"\n[XUẤT FILE] Đã lưu {len(records)} bản ghi khối vào: {out_csv}")

    # 2. Export summary CSV
    summary_csv = os.path.join(raw_dir, "rq3_workload_summary.csv")
    sum_fields = [
        "load_factor", "algorithm", "variant", "tau", "churn_cycles", "total_blocks",
        "total_churn_time_ms", "median_block_ms", "max_block_ms", "rebuild_count",
        "rebuild_overhead_ms", "average_dib", "max_dib", "tombstone_ratio", "empty_ratio"
    ]
    with open(summary_csv, "w", newline="", encoding="utf-8") as f:
        writer = csv.DictWriter(f, fieldnames=sum_fields)
        writer.writeheader()
        writer.writerows(summary_records)
    print(f"[XUẤT FILE] Đã lưu bảng tổng hợp workload vào: {summary_csv}")

    # Print summary table to console
    print("\n" + "=" * 105)
    print("       BẢNG KẾT QUẢ PHÂN TÍCH WORKLOAD CHURN & ĐỘ ĐỘT BIẾN KHỐI CHO RQ3 (C3) - 26/10/2026       ")
    print("=" * 105)
    header = f"{'Load':^6} | {'Algorithm':<14} | {'Total ms':>10} | {'Med (ms)':>8} | {'Max (ms)':>8} | {'Rebuilds':>8} | {'Avg DIB':>8} | {'Max DIB':>7} | {'TOMB %':>8}"
    print(header)
    print("-" * 105)
    for r in summary_records:
        row_str = f"{r['load_factor']:^6.2f} | {r['algorithm']:<14} | {r['total_churn_time_ms']:>10.2f} | {r['median_block_ms']:>8.2f} | {r['max_block_ms']:>8.2f} | {r['rebuild_count']:>8d} | {r['average_dib']:>8.4f} | {r['max_dib']:>7d} | {r['tombstone_ratio']*100:>7.2f}%"
        print(row_str)
    print("=" * 105)

    return summary_records

if __name__ == "__main__":
    repo_root = os.path.abspath(os.path.join(os.path.dirname(__file__), ".."))
    run_workload_profiling(repo_root)
